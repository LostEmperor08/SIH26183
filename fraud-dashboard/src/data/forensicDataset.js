/**
 * Helper to convert a linear Multi-Chain case into graph nodes, edges, metrics, and ledgerRows
 */
export function convertChainCaseToGraph(chainCase) {
  const steps = chainCase.steps;
  const nodes = steps.map((s, idx) => ({
    id: `node-${s.type}-${idx}`,
    address: s.address,
    label: s.entity,
    category: s.role,
    typology: s.note,
    fir: chainCase.fir,
    state: chainCase.chainName,
    type: s.type,
    amountEth: parseFloat(s.volume) || 5.0,
    amountStr: s.volume,
    amountInrStr: s.inr,
    timestamp: s.time,
    inflowEth: parseFloat(s.volume) || 5.0,
    outflowEth: s.type === "vasp" ? 0 : parseFloat(s.volume) || 5.0,
    retainedEth: s.type === "vasp" ? parseFloat(s.volume) || 5.0 : 0.0,
    primarySender: idx > 0 ? steps[idx - 1].address : "Victim Complaint",
    primaryReceiver: idx < steps.length - 1 ? steps[idx + 1].address : chainCase.nearestVasp,
    complianceEmail: s.type === "vasp" ? chainCase.complianceEmail : null,
    x: 120 + idx * 270,
    y: 220,
  }));

  const edges = [];
  for (let i = 0; i < steps.length - 1; i++) {
    edges.push({
      from: `node-${steps[i].type}-${i}`,
      to: `node-${steps[i + 1].type}-${i + 1}`,
      amountEth: parseFloat(steps[i].volume) || 5.0,
      amountStr: steps[i].volume,
      txHash: steps[i + 1].txHash,
      hop: i + 1,
    });
  }

  const ledgerRows = steps.map((s, idx) => ({
    wallet: s.address,
    shortWallet: `${s.address.substring(0, 8)}...${s.address.substring(s.address.length - 6)}`,
    fir: chainCase.fir,
    hop: idx,
    amountEth: parseFloat(s.volume) || 5.0,
    amountStr: s.volume,
    amountInr: s.inr,
    timestamp: s.time,
    destinationVasp: chainCase.nearestVasp,
    vaspWallet: steps[steps.length - 1].address,
    typology: s.role,
    status: s.type === "vasp" ? "Attributed Endpoint" : "Transit",
    nodeId: `node-${s.type}-${idx}`,
  }));

  return {
    caseId: chainCase.id,
    title: `${chainCase.title} (${chainCase.chainName})`,
    chain: chainCase.chain,
    currency: chainCase.currency,
    convergenceAlert: null,
    metrics: {
      totalVolumeEth: parseFloat(chainCase.reportedLoss) || 5.08,
      totalVolumeStr: chainCase.reportedLoss,
      totalVolumeInrStr: chainCase.lossInr,
      totalVolumeInr: parseFloat(chainCase.lossInr.replace(/[^\d.]/g, "")) || 1219200,
      nearestVasp: {
        name: chainCase.nearestVasp,
        subtext: chainCase.vaspType,
        fiuRegistered: chainCase.fiuRegistered,
        slaNotice: chainCase.fiuRegistered ? "< 4h PMLA Statutory Notice" : "< 24h LEA Freeze Notice",
      },
      velocity: {
        maxDepth: `${chainCase.hopsCount} Hops`,
        avgSpeed: chainCase.traversalTime,
        layeringMethod: "Rapid Mule Transit",
      },
      syndicateRisk: {
        score: 88,
        level: "CRITICAL",
        type: chainCase.title,
      },
    },
    nodes,
    edges,
    ledgerRows,
  };
}

