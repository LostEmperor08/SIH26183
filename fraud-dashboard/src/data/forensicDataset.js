export function formatINR(val) {
  if (typeof val === 'string') return val;
  const inr = typeof val === 'number' ? (val < 1000 ? val * 240000 : val) : 1219200;
  return new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 0 }).format(inr);
}

export function formatUSD(val) {
  if (typeof val === 'string') return val;
  const usd = typeof val === 'number' ? (val < 1000 ? val * 2600 : val) : 13200;
  return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 0 }).format(usd);
}


